#include <stdio.h>

int main()
{
   int a = 25, b = 5;

   printf("a = 25\n");
   printf("b = 5\n\n");

   printf("a < b\t %d\n", a < b);
   printf("a > b\t %d\n", a > b);
   printf("a <= b\t %d\n", a <= b);
   printf("a >= b\t %d\n", a >= b);
   printf("a == b\t %d\n", a == b);
   printf("a != b\t %d\n", a != b);

   return 0;
}
